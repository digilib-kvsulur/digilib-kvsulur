import { useCallback, useEffect, useMemo, useState } from "react";
import { Bar, BarChart, CartesianGrid, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { BarChart3, BookOpenCheck, CalendarRange, Download, Layers, Loader2, Target, Trophy } from "lucide-react";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { toast } from "sonner";
import { fetchLearningReport } from "./api";
import type { LearningReport as LearningReportData } from "./types";

function isoDate(date: Date) {
  return date.toISOString().slice(0, 10);
}

function monthStart() {
  const now = new Date();
  return isoDate(new Date(now.getFullYear(), now.getMonth(), 1));
}

function daysAgo(days: number) {
  const now = new Date();
  now.setDate(now.getDate() - days);
  return isoDate(now);
}

function Stat({ label, value, hint, icon: Icon }: { label: string; value: string; hint?: string; icon: typeof Target }) {
  return (
    <Card className="rounded-2xl shadow-none">
      <CardContent className="p-3.5">
        <div className="flex items-center gap-2 text-muted-foreground"><Icon className="h-4 w-4" /><p className="text-[11px] font-medium uppercase tracking-wide">{label}</p></div>
        <p className="mt-1.5 text-2xl font-black">{value}</p>
        {hint && <p className="text-[11px] text-muted-foreground">{hint}</p>}
      </CardContent>
    </Card>
  );
}

export default function LearningReport({ studentName, studentClass }: { studentName?: string; studentClass?: string }) {
  const [from, setFrom] = useState(monthStart());
  const [to, setTo] = useState(isoDate(new Date()));
  const [report, setReport] = useState<LearningReportData | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const load = useCallback(async (start = from, end = to) => {
    setLoading(true);
    setError("");
    try {
      setReport(await fetchLearningReport(start, end));
    } catch (e: any) {
      setError(e?.message || "The report could not be loaded.");
    } finally {
      setLoading(false);
    }
  }, [from, to]);

  useEffect(() => {
    void load(monthStart(), isoDate(new Date()));
    // The initial report always covers the current month.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const chartData = useMemo(
    () => (report?.daily || []).map((day) => ({
      ...day,
      label: new Date(`${day.date}T00:00:00`).toLocaleDateString(undefined, { day: "numeric", month: "short" }),
    })),
    [report],
  );

  const downloadPdf = () => {
    if (!report) return;
    const doc = new jsPDF("portrait");
    doc.setFont("Helvetica", "bold");
    doc.setFontSize(18);
    doc.text("Learning Report", 14, 18);
    doc.setFont("Helvetica", "normal");
    doc.setFontSize(10);
    doc.text(`${studentName || "Student"}${studentClass ? ` · Class ${studentClass}` : ""}`, 14, 26);
    doc.text(`${report.from} to ${report.to}`, 14, 32);

    autoTable(doc, {
      startY: 38,
      head: [["Measure", "Value"]],
      body: [
        ["Study time", `${report.study_minutes} minutes across ${report.study_sessions} sessions`],
        ["Chapters completed", String(report.chapters_completed)],
        ["Practice questions", `${report.practice_attempts} answered · ${report.practice_accuracy}% correct`],
        ["Flashcard reviews", `${report.flashcard_reviews} reviews · ${report.flashcards_practised} cards`],
        ["Mock tests", `${report.mock_attempts} submitted · best ${report.best_mock_percent}%`],
        ["Books read", String(report.books_read)],
        ["Points earned", String(report.points_earned)],
      ],
      theme: "grid",
      headStyles: { fillColor: [79, 70, 229] },
    });

    const finalY = (doc as any).lastAutoTable?.finalY || 100;
    autoTable(doc, {
      startY: finalY + 8,
      head: [["Date", "Minutes", "Practice", "Reviews"]],
      body: report.daily.slice(-31).map((day) => [day.date, String(day.minutes), String(day.practice), String(day.reviews)]),
      theme: "striped",
      headStyles: { fillColor: [16, 185, 129] },
    });

    doc.setFontSize(8);
    doc.setTextColor(120);
    doc.text("Generated by DLMS · Learning report", 14, doc.internal.pageSize.getHeight() - 10);
    doc.save(`learning-report-${report.from}-to-${report.to}.pdf`);
  };

  return (
    <div className="space-y-3">
      <Card className="rounded-2xl border-border/70 shadow-none">
        <CardHeader className="pb-2">
          <CardTitle className="flex items-center gap-2 text-base"><CalendarRange className="h-4 w-4 text-primary" /> Choose a period</CardTitle>
        </CardHeader>
        <CardContent className="space-y-3">
          <div className="grid gap-2 sm:grid-cols-[1fr_1fr_auto]">
            <div>
              <Label htmlFor="report-from" className="text-xs">From</Label>
              <Input id="report-from" type="date" value={from} max={to} onChange={(event) => setFrom(event.target.value)} className="mt-1 min-h-10 rounded-xl" />
            </div>
            <div>
              <Label htmlFor="report-to" className="text-xs">To</Label>
              <Input id="report-to" type="date" value={to} min={from} max={isoDate(new Date())} onChange={(event) => setTo(event.target.value)} className="mt-1 min-h-10 rounded-xl" />
            </div>
            <div className="flex items-end gap-2">
              <Button type="button" className="min-h-10 rounded-xl" disabled={loading} onClick={() => void load(from, to)}>Update</Button>
              <Button type="button" variant="outline" className="min-h-10 rounded-xl" onClick={downloadPdf} disabled={!report}>
                <Download className="mr-1.5 h-4 w-4" /> PDF
              </Button>
            </div>
          </div>
          <div className="flex flex-wrap gap-2">
            <Button type="button" size="sm" variant="ghost" className="h-9 rounded-lg" onClick={() => { const start = monthStart(); const end = isoDate(new Date()); setFrom(start); setTo(end); void load(start, end); }}>This month</Button>
            <Button type="button" size="sm" variant="ghost" className="h-9 rounded-lg" onClick={() => { const start = daysAgo(29); const end = isoDate(new Date()); setFrom(start); setTo(end); void load(start, end); }}>Last 30 days</Button>
            <Button type="button" size="sm" variant="ghost" className="h-9 rounded-lg" onClick={() => { const start = daysAgo(89); const end = isoDate(new Date()); setFrom(start); setTo(end); void load(start, end); }}>Last 90 days</Button>
          </div>
        </CardContent>
      </Card>

      {loading ? (
        <Card className="rounded-2xl shadow-none"><CardContent className="flex items-center gap-2 p-6 text-sm text-muted-foreground"><Loader2 className="h-4 w-4 animate-spin" /> Building your report…</CardContent></Card>
      ) : error ? (
        <Card className="rounded-2xl shadow-none"><CardContent className="p-6 text-center"><p role="alert" className="text-sm text-destructive">{error}</p><Button variant="outline" className="mt-3 min-h-10 rounded-xl" onClick={() => void load(from, to)}>Try again</Button></CardContent></Card>
      ) : report ? (
        <>
          <div className="grid grid-cols-2 gap-2 sm:grid-cols-3">
            <Stat label="Study time" value={`${report.study_minutes}m`} hint={`${report.study_sessions} sessions`} icon={CalendarRange} />
            <Stat label="Chapters" value={String(report.chapters_completed)} hint="marked complete" icon={BookOpenCheck} />
            <Stat label="Accuracy" value={`${report.practice_accuracy}%`} hint={`${report.practice_attempts} questions`} icon={Target} />
            <Stat label="Flashcards" value={String(report.flashcard_reviews)} hint={`${report.flashcards_practised} cards reviewed`} icon={Layers} />
            <Stat label="Mock tests" value={String(report.mock_attempts)} hint={`best ${report.best_mock_percent}%`} icon={Trophy} />
            <Stat label="Points" value={String(report.points_earned)} hint="earned in this period" icon={BarChart3} />
          </div>

          <Card className="rounded-2xl shadow-none">
            <CardHeader className="pb-2">
              <CardTitle className="text-base">Daily activity</CardTitle>
              <p className="text-xs text-muted-foreground">Study minutes per day. Hover or tap a bar for details.</p>
            </CardHeader>
            <CardContent>
              {chartData.length === 0 ? (
                <p className="py-8 text-center text-sm text-muted-foreground">No activity in this period.</p>
              ) : (
                <div className="h-56 w-full">
                  <ResponsiveContainer width="100%" height="100%">
                    <BarChart data={chartData} margin={{ top: 8, right: 8, left: -20, bottom: 0 }}>
                      <CartesianGrid strokeDasharray="3 3" vertical={false} opacity={0.3} />
                      <XAxis dataKey="label" tick={{ fontSize: 10 }} interval="preserveStartEnd" minTickGap={24} />
                      <YAxis tick={{ fontSize: 10 }} allowDecimals={false} />
                      <Tooltip
                        contentStyle={{ borderRadius: 12, fontSize: 12 }}
                        formatter={(value: number, name: string) => [name === "minutes" ? `${value} min` : value, name === "minutes" ? "Study time" : name === "practice" ? "Practice" : "Reviews"]}
                        labelFormatter={(label) => String(label)}
                      />
                      <Bar dataKey="minutes" fill="#4f46e5" radius={[4, 4, 0, 0]} />
                    </BarChart>
                  </ResponsiveContainer>
                </div>
              )}
            </CardContent>
          </Card>

          <Card className="rounded-2xl shadow-none">
            <CardHeader className="pb-2"><CardTitle className="text-base">What this means</CardTitle></CardHeader>
            <CardContent className="space-y-2 text-sm text-muted-foreground">
              <p>
                {report.study_minutes === 0
                  ? "No study sessions were logged in this period. A 20-minute focused session is enough to restart the habit."
                  : `You logged ${report.study_minutes} minutes across ${report.study_sessions} sessions.`}
              </p>
              <p>
                {report.practice_attempts === 0
                  ? "No practice questions were answered. Try a chapter practice set to start building mastery data."
                  : `Practice accuracy is ${report.practice_accuracy}%. ${report.practice_accuracy >= 75 ? "That is a strong base — keep mixing in harder questions." : "Review the explanations for wrong answers before attempting more."}`}
              </p>
              <p>
                {report.flashcard_reviews === 0
                  ? "No flashcard reviews yet. Ten minutes of review is the highest-return habit for memory."
                  : `${report.flashcard_reviews} flashcard reviews kept ${report.flashcards_practised} cards active.`}
              </p>
            </CardContent>
          </Card>
        </>
      ) : null}
    </div>
  );
}
